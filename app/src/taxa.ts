export const groupOf = (s: Species): string | null => {
  const genus = s.sci.split(' ')[0];
  if (GENUS_GROUP[genus]) return GENUS_GROUP[genus];
  return (s.family && FAMILY[s.family]?.group) || null;
};
export const familyEn = (s: Species): string => (s.family && FAMILY[s.family]?.en) || s.family || '';
export const groupLabel = (g: string) => BIRD_GROUPS.find(([k]) => k === g)?.[1] || g;

