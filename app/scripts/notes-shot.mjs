import { chromium } from 'playwright-core';
// Species notes: add, keep after reload, find by search, marker in the list, edit, delete.
// Usage: node scripts/notes-shot.mjs <outdir>
const out = process.argv[2];
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const ctx = await browser.newContext({ viewport: { width: 412, height: 915 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const page = await ctx.newPage();
const errs = [];
page.on('pageerror', (e) => errs.push(e.message));
page.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
page.on('dialog', (d) => d.accept());
const base = 'http://localhost:5180/Pidwa_checklist/#/';
await page.goto(base + 'species/tockus-leucomelas', { waitUntil: 'networkidle' });
await page.waitForTimeout(1200);
await page.fill('.notenew textarea', 'Le guide dit: niche dans un trou, zazou unique');
await page.click('.notenew .btn');
await page.waitForTimeout(300);
await page.fill('.notenew textarea', 'Second note');
await page.click('.notenew .btn');
await page.waitForTimeout(300);
await page.locator('.notenew').scrollIntoViewIfNeeded();
await page.screenshot({ path: `${out}/n-species.png` });
await page.reload({ waitUntil: 'networkidle' });
await page.waitForTimeout(1200);
console.log('after reload:', await page.locator('.note1').count(), await page.locator('.note1 .body').allTextContents());
await page.goto(base + 'list', { waitUntil: 'networkidle' });
await page.waitForTimeout(800);
await page.fill('input[type=text], input[type=search]', 'zazou');
await page.waitForTimeout(300);
console.log('search:', await page.locator('.sp-row .fr').allTextContents(), 'marker:', await page.locator('.hasnote').count());
await page.screenshot({ path: `${out}/n-list.png` });
await page.goto(base + 'species/tockus-leucomelas', { waitUntil: 'networkidle' });
await page.waitForTimeout(1000);
await page.locator('.note1').first().click();
await page.fill('.notenew >> nth=1 >> textarea', 'Second note edited');
await page.click('.notenew >> nth=1 >> .btn:has-text("Save")');
await page.waitForTimeout(300);
console.log('edited:', await page.locator('.note1 .body').allTextContents());
await page.locator('.note1').first().click();
await page.click('[aria-label="Delete note"]');
await page.waitForTimeout(300);
console.log('deleted:', await page.locator('.note1 .body').allTextContents());
console.log('errors:', errs);
await browser.close();
